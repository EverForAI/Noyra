"""Single source of truth for the externally supported HTTP route surface."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

RouteRole = Literal["none", "read", "operator", "export"]

# These failures are produced by the HTTP boundary before (or around) the
# individual route handler.  Keeping them explicit prevents the OpenAPI
# inventory from claiming that a route can only return its happy-path status.
GLOBAL_API_ERROR_RESPONSES: tuple[int, ...] = (429, 503)
JSON_REQUEST_ERROR_RESPONSES: tuple[int, ...] = (411, 413)


@dataclass(frozen=True)
class APIRouteContract:
    method: str
    path: str
    role: RouteRole
    responses: tuple[int, ...]
    request_json: bool = False

    def __post_init__(self) -> None:
        if self.method not in {"GET", "POST"} or (
            not self.path.startswith("/health") and not self.path.startswith("/api/v1/")
        ):
            raise ValueError("invalid API route contract")
        if not self.responses or any(type(code) is not int for code in self.responses):
            raise ValueError("API route contract requires response statuses")

    @property
    def inherited_responses(self) -> tuple[int, ...]:
        """Responses emitted by the shared HTTP boundary for this route."""
        if not self.path.startswith("/api/v1/"):
            return ()
        inherited = list(GLOBAL_API_ERROR_RESPONSES)
        if self.method == "POST" and self.request_json:
            inherited.extend(JSON_REQUEST_ERROR_RESPONSES)
        return tuple(inherited)

    @property
    def effective_responses(self) -> tuple[int, ...]:
        """Route-specific plus inherited boundary responses, without duplicates."""
        return tuple(dict.fromkeys((*self.responses, *self.inherited_responses)))


def _get(path: str, role: RouteRole = "none", *responses: int) -> APIRouteContract:
    return APIRouteContract("GET", path, role, responses or (200,))


def _post(
    path: str,
    role: RouteRole = "operator",
    *responses: int,
    request_json: bool = True,
) -> APIRouteContract:
    return APIRouteContract("POST", path, role, responses or (200,), request_json)


