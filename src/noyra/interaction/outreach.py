"""Recipient-specific consent for general autonomous expression."""

from __future__ import annotations

import re
from email.errors import HeaderParseError
from email.headerregistry import Address
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from noyra.core.errors import IntegrityError
from noyra.core.redaction import redact_secret_text

POLICY_KEY = "_autonomous_recipient_policy_v1"
MAX_RECIPIENTS = 32
FIXED_RECIPIENT_KEYS = ("recipient", "chat_id", "target", "to")


class OutreachDenied(PermissionError):
    """The draft or delivery lacks current recipient permission."""


def _plain(value: str) -> bool:
    return bool(value and value == value.strip() and value.isprintable())


def _mailbox(value: str) -> str:
    try:
        address = Address(addr_spec=value)
        if (
            not value.isascii()
            or not address.username
            or not address.domain
            or address.addr_spec != value
            or not re.fullmatch(r"[A-Za-z0-9.-]+", address.domain)
        ):
            raise ValueError("invalid mailbox")
    except (ValueError, IndexError, HeaderParseError):
        raise ValueError("one plain ASCII mailbox is required") from None
    return f"{address.username}@{address.domain.lower()}"


class OutreachChange(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)

    operation: Literal["authorize", "revoke"]
    recipient: str = Field(min_length=1, max_length=512)
    reason: str = Field(min_length=1, max_length=256)
    expected_authorization_id: str | None = Field(default=None, max_length=80)
    confirm_opt_in: bool = False
    operator_name: str | None = Field(default=None, min_length=1, max_length=100)
    opt_out_email: str | None = Field(default=None, min_length=1, max_length=254)

    @model_validator(mode="after")
    def validate_change(self) -> OutreachChange:
        if not _plain(self.recipient) or not _plain(self.reason):
            raise ValueError("recipient and reason must be plain text")
        if self.operation == "authorize":
            if not self.confirm_opt_in or not self.operator_name or not self.opt_out_email:
                raise ValueError("recipient opt-in and operator contact are required")
            if (
                not _plain(self.operator_name)
                or redact_secret_text(self.operator_name) != self.operator_name
            ):
                raise ValueError("operator name must be public plain text")
            _mailbox(self.opt_out_email)
        elif (
            self.confirm_opt_in or self.operator_name is not None or self.opt_out_email is not None
        ):
            raise ValueError("revocation does not accept opt-in or disclosure fields")
        return self


class OutreachAuthorization(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)

    authorization_id: str = Field(pattern=r"^outreach_[0-9a-f]{32}$")
    active: bool
    operator_name: str | None = Field(max_length=100)
    opt_out_email: str | None = Field(max_length=254)

    @model_validator(mode="after")
    def validate_notice(self) -> OutreachAuthorization:
        if self.active:
            if not self.operator_name or not self.opt_out_email or not _plain(self.operator_name):
                raise ValueError("active authorization must have an operator contact")
            _mailbox(self.opt_out_email)
        elif self.operator_name is not None or self.opt_out_email is not None:
            raise ValueError("revoked authorization must not retain disclosure fields")
        return self

    def notice(self) -> str:
        return (
            "This message was generated by Noyra, an AI system.\n"
            f"Operator: {self.operator_name}. To stop proactive messages, contact "
            f"{self.opt_out_email}.\n\n"
        )


def recipient_key(channel: str, recipient: str) -> str:
    if not _plain(recipient) or len(recipient) > 512:
        raise ValueError("invalid outreach recipient")
    return _mailbox(recipient) if channel == "email" else recipient


def route_allows(config: dict[str, Any], channel: str, recipient: str) -> bool:
    if config.get("autonomous_send", True) is not True:
        return False
    scope = config.get("allowed_recipients")
    fixed = [str(config[key]).strip() for key in FIXED_RECIPIENT_KEYS if config.get(key)]
    # Custom Feishu webhooks target a fixed chat, not the supplied recipient.
    if channel == "feishu" and str(config.get("delivery_mode", "")).lower() != "app" and not fixed:
        return False
    try:
        return all(recipient_key(channel, item) == recipient for item in fixed) and (
            scope is None
            or (
                isinstance(scope, str)
                and (
                    not scope.strip()
                    or recipient
                    in {
                        recipient_key(channel, item.strip())
                        for item in scope.split(",")
                        if item.strip()
                    }
                )
            )
        )
    except ValueError:
        return False


def recipient_policy(config: dict[str, Any], channel: str) -> dict[str, OutreachAuthorization]:
    raw = config.get(POLICY_KEY, {})
    if not isinstance(raw, dict) or len(raw) > MAX_RECIPIENTS:
        raise IntegrityError("invalid autonomous recipient policy")
    try:
        result = {}
        for recipient, entry in raw.items():
            if not isinstance(recipient, str) or recipient_key(channel, recipient) != recipient:
                raise ValueError("invalid canonical recipient")
            result[recipient] = OutreachAuthorization.model_validate(entry)
        return result
    except ValueError:
        raise IntegrityError("invalid autonomous recipient policy") from None


def eligible_recipients(config: dict[str, Any], channel: str) -> list[str]:
    return sorted(
        recipient
        for recipient, entry in recipient_policy(config, channel).items()
        if entry.active and route_allows(config, channel, recipient)
    )
